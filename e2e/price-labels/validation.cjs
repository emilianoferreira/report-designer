const { expect } = require('@playwright/test');
module.exports = async (page, newTemplate) => {
  const button = name => page.getByRole('button', {name, exact:true});
  const tab = name => page.locator('app-price-label-properties').getByRole('button',{name,exact:true});
  await newTemplate();
  await page.locator('.price-content').click(); await tab('Datos').click();
  const decimals=page.getByLabel('Decimales',{exact:true});
  await decimals.fill('-1'); await decimals.press('Tab');
  await expect(page.getByRole('alert')).toContainText('Decimales');
  await expect(page.locator('.price-content')).toContainText('4.200,00');
  await decimals.fill('2'); await decimals.press('Tab');
  await page.locator('app-price-label-properties').getByLabel('Precio',{exact:true}).fill('article.missing');
  await page.locator('app-price-label-properties').getByLabel('Precio',{exact:true}).press('Tab');
  await button('Vista previa').click();
  await expect(button('Imprimir')).toBeDisabled(); await expect(button('Exportar HTML')).toBeDisabled();
  await expect(page.getByRole('alert').first()).toContainText('precio ausente');
  await expect(page.getByRole('alert')).toHaveCount(4);
  await button('Diseño').click(); await newTemplate();
  await page.locator('.barcode-content').click(); await tab('Datos').click();
  await page.getByRole('combobox',{name:/^Tipo/}).selectOption('EAN8');
  await button('Vista previa').click(); await expect(button('Imprimir')).toBeDisabled();
  await expect(page.getByRole('alert').first()).toContainText('EAN8');
  await button('Diseño').click(); await newTemplate(); await button('Vista previa').click();
  await expect(button('Imprimir')).toBeEnabled();
  const copies=page.getByLabel('Copias por articulo'); await copies.fill('100'); await copies.press('Tab');
  await expect(button('Imprimir')).toBeDisabled(); await expect(page.getByRole('alert')).toContainText('99');
  await copies.fill('2'); await copies.press('Tab'); await expect(button('Imprimir')).toBeEnabled();
  await button('Diseño').click(); await page.locator('.image-content').click(); await tab('Datos').click();
  await page.getByRole('combobox',{name:/^Origen/}).selectOption('url');
  const url=page.getByLabel('URL',{exact:true}); await url.fill('https://missing.example.test/image.png'); await url.press('Tab');
  await button('Vista previa').click(); await expect(page.getByRole('alert').first()).toContainText('imagen');
  await expect(button('Imprimir')).toBeDisabled(); await expect(button('Exportar HTML')).toBeDisabled();
  await button('Diseño').click(); await newTemplate(); await button('Vista previa').click();
  await expect(button('Imprimir')).toBeEnabled(); await button('Diseño').click();
  console.log('PASS: numeric draft validation, missing prices, invalid barcode, copy bounds, broken images and recovery.');
};
